#!/usr/bin/env bash
# create-seed-file.sh

HEADER="[MariaDB]"

set -e

if [ "$1" = "" ]; then
  echo "Usage: $0 <output-file.sql>"
  exit 1
fi

OUTPUT_FILE="$1"

date +"-- Generated on %Y-%m-%d %H:%M:%S" > "$OUTPUT_FILE"
date +"-- by create-seed-file.sh" >> "$OUTPUT_FILE"
date +"-- Do not edit this file manually" >> "$OUTPUT_FILE"

get_randoms_player_id() {
  ids=$(shuf -i 100000-9999999 -n $1 | tr '\n' ' ')
  echo "$ids"
}

get_random_number() {
  min=$1
  max=$2
  echo $(( $(od -An -N2 -tu2 < /dev/urandom | tr -d ' ') % (max - min + 1) + min ))
}

main() {
  NB_DUNGEONS=500
  POSITIONS=$(for i in $(seq 1 $NB_DUNGEONS); do echo "$(get_random_number 1 1200),$(get_random_number 1 1200)"; done | sort -u | head -n $NB_DUNGEONS)
  PLAYER_IDS=$(get_randoms_player_id $((NB_LINES / 10)))
  NB_LINES=$((NB_DUNGEONS))
  for POS in $POSITIONS; do
    KID=$(get_random_number 1 3)
    POS_X=$(echo "$POS" | cut -d',' -f1)
    POS_Y=$(echo "$POS" | cut -d',' -f2)
    ATTACK_COOLDOWN=$(get_random_number 1 30)
    PLAYER_ID=$(echo "$PLAYER_IDS" | tr ' ' '\n' | shuf -n 1)
    if [ -z "$PLAYER_ID" ]; then
      PLAYER_ID="NULL"
    fi
    TOTAL_ATTACK_COUNT=$(get_random_number 1 100)
    echo "INSERT INTO dungeons (kid, position_x, position_y, attack_cooldown, player_id, total_attack_count) VALUES ($KID, $POS_X, $POS_Y, $ATTACK_COOLDOWN, $PLAYER_ID, $TOTAL_ATTACK_COUNT);"

    LAST_ATTACK_AT=$(( $(date +%s) - RANDOM % 10800 ))
    PLAYER_ID=$(echo "$PLAYER_IDS" | tr ' ' '\n' | shuf -n 1)
    if [ -z "$PLAYER_ID" ]; then
      PLAYER_ID="NULL"
    fi
    echo "INSERT INTO dungeon_player_state (kid, position_x, position_y, player_id, last_attack_at) VALUES ($KID, $POS_X, $POS_Y, $PLAYER_ID, FROM_UNIXTIME($LAST_ATTACK_AT));"
  done
} >> "$OUTPUT_FILE"

echo "$HEADER Creating seed file..."
main
echo "$HEADER Seed file created at: $OUTPUT_FILE"
